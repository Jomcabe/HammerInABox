"""Build real CAT-SOOP course files from the public placeholder content."""
import json
from html import escape
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'content/courses.json').read_text())
DEST = ROOT / 'classroom/courses'

def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip()+'\n')

def qsource(q):
    common = f'csq_name = {q["id"]!r}\ncsq_prompt = {escape(q["prompt"])!r}\ncsq_npoints = 1\ncsq_grading_mode = "legacy"\ncsq_explanation = {escape(q["explanation"])!r}\n'
    if q['type'] == 'choice':
        return '<question multiplechoice>\n'+common+f'csq_renderer = "radio"\ncsq_options = {q["options"]!r}\ncsq_soln_mode = "index"\ncsq_soln = {q["answer"]!r}\n</question>\n'
    return '<question smallbox>\n'+common+f'''csq_soln = {str(q["answer"])!r}
csq_size = 16
csq_prompt += {(' Enter the number in '+q['unit']+'.')!r}
def csq_check_function(sub, sol):
    import math
    try:
        value = float(sub.strip())
        correct = math.isfinite(value) and abs(value - float(sol)) <= {q['tolerance']!r}
    except (ValueError, TypeError, OverflowError):
        return 0, "Enter a number without units."
    return (1, {escape(q['explanation'])!r}) if correct else (0, "Not quite yet. Check your relationship and units, then try again.")
</question>
'''

for c in DATA['courses']:
    folder = DEST / c['id']
    write(folder/'preload.py', f'''# Generated by scripts/generate_catsoop.py. Edit content/courses.json first.
cs_header = "Gubber"
cs_long_name = {c['title']!r}
cs_title = {('Gubber | '+c['title'])!r}
cs_content_header = {c['title']!r}
cs_base_color = "#173e33"
cs_auth_type = "login"
cs_view_without_auth = True
cs_default_role = "Guest"
cs_permissions = {{
    "Guest": ["view"],
    "Student": ["view", "submit"],
    "Instructor": ["view_all", "submit_all", "impersonate", "admin", "whdw", "grade"],
}}
cs_release_date = "ALWAYS"
cs_due_date = "NEVER"
cs_top_menu = [
    {{"text": "Classroom", "link": "/#/{c['id']}/overview"}},
    {{"text": "Course home", "link": "COURSE"}},
    {{"text": "Schedule", "link": "COURSE/schedule"}},
    {{"text": "Course guide", "link": "COURSE/guide"}},
]
cs_footer = "Independent sample classroom by Jose Carvajal-Beltran. All content is filler. Not an official MIT course."
''')
    home=f'# {c["code"]}: {c["title"]}\n\n{c["description"]}\n\nThis is a sample course for future work. Dates, policies, and assignments are placeholders.\n\nGuests can read lessons. An enrolled account is required to submit practice to this server.\n\n'
    for u in c['units']:
        home+=f'## Module {u["number"]:02d}: {u["title"]}\n\n{u["description"]}\n\n[Read the lesson](COURSE/{u["id"]}) · [Try the practice](COURSE/{u["id"]}/practice)\n\n'
        l=u['lesson']
        write(folder/u['id']/'preload.py',f'cs_content_header = {u["title"]!r}\ncs_title = {u["title"]!r}\n')
        write(folder/u['id']/'content.catsoop',f'''# {l['heading']}

{l['body']}

## A simple example

{l['example']}

**Useful relationship:** {l['formula']}

## Pause and try

{l['activity']}

[Try the practice](COURSE/{u['id']}/practice) · [Back to the learning path](COURSE)
''')
        write(folder/u['id']/'practice/preload.py',f'cs_content_header = {u["assignment"]["title"]!r}\ncs_title = {u["assignment"]["title"]!r}\ncsq_grading_mode = "legacy"\n')
        write(folder/u['id']/'practice/content.catsoop',f'# {u["assignment"]["title"]}\n\nSample practice. No deadline. Each question is worth one sample point.\n\n'+ '\n'.join(qsource(q) for q in u['assignment']['questions'])+f'\n[Review the lesson](COURSE/{u["id"]})\n')
    write(folder/'content.catsoop',home)
    write(folder/'schedule/content.catsoop','# Sample schedule\n\nDates and deadlines are not set.\n\n'+'\n'.join(f'* Week {u["number"]}: [{u["title"]}](COURSE/{u["id"]})' for u in c['units']))
    write(folder/'guide/content.catsoop',f'''# Sample course guide

{c['description']}

## Learning approach

Read each lesson, try the activity, then complete the sample practice.
Practice uses built-in multiple-choice and short-answer questions.

## Future policies

Add instructor contact, meeting times, office hours, grading policy,
collaboration rules, and accessibility arrangements before a real course begins.
No real course dates or policies are set in this template.

## Accounts and enrollment

Guests may read this sample course. Enrollment is assigned by the server operator.
A registered account alone does not grant submission or instructor permissions.

[Return to the course](COURSE)
''')
print(f'Generated {len(DATA["courses"])} CAT-SOOP courses in classroom/courses/')
